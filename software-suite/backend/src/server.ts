import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { pool } from './db.js';
import authRoutes from './routes/auth.js';
import workspaceRoutes from './routes/workspaces.js';
import crmRoutes from './routes/crm.js';
import profileRoutes from './routes/profile.js';
import recordRoutes from './routes/records.js';
import { authenticate, requireWorkspace } from './middleware/auth.js';
import { errorHandler } from './middleware/errors.js';

const app=express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({origin:(process.env.FRONTEND_ORIGIN||process.env.CORS_ORIGIN)?.split(',').map(s=>s.trim())||'http://localhost:5173'}));
app.use(express.json({limit:'10mb'}));
app.use(rateLimit({windowMs:15*60*1000,limit:300,standardHeaders:true,legacyHeaders:false}));
const base='/api/business-suite';
app.get(`${base}/health`,async(_req,res)=>{try{await pool.query('SELECT 1');res.json({status:'ok',service:'happy-business-suite-api',database:'connected'});}catch{res.status(503).json({status:'unavailable',message:'Database connection is unavailable.'});}});
app.use(`${base}/auth`,authRoutes);
app.use(`${base}/workspaces`,authenticate,workspaceRoutes);
app.use(base,authenticate,requireWorkspace,crmRoutes);
app.use(base,authenticate,requireWorkspace,profileRoutes);
app.use(base,authenticate,requireWorkspace,recordRoutes);
app.use((_req,res)=>res.status(404).json({message:'The requested endpoint was not found.'}));
app.use(errorHandler);
const port=Number(process.env.PORT||5000);
app.listen(port,()=>console.log(`Happy Business Suite API listening on port ${port}`));
